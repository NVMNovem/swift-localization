import SwiftLocalization

/// Emits a catalog as Swift source that rebuilds it with the public
/// `SwiftLocalization` API.
///
/// Output depends only on the catalog and the emitter's properties: keys,
/// locales, and variation cases are sorted, and nothing host-specific is
/// written.
package struct SwiftCatalogEmitter: Sendable {
    /// Bumped whenever the shape of the generated source changes.
    package static let formatVersion = 1

    /// The name of the generated static property on `LocalizationCatalog`.
    package var propertyName: String
    /// The file name of the source catalog, without directories.
    package var sourceFileName: String
    /// The access level of the generated property.
    package var accessLevel: String

    /// Throws when `propertyName` is not a valid Swift identifier, so that it
    /// is never written into generated source unchecked.
    package init(propertyName: String, sourceFileName: String, accessLevel: String = "internal") throws(NameError) {
        guard Self.isValidPropertyName(propertyName) else { throw NameError.invalidName(propertyName) }
        self.propertyName = propertyName
        self.sourceFileName = sourceFileName
        self.accessLevel = accessLevel
    }

    /// A lower-camel-case Swift identifier for a catalog file name. This is
    /// the only place accessor names are derived.
    ///
    /// The last extension is dropped and every other character that cannot
    /// be part of an identifier separates words: `Localizable.xcstrings`
    /// becomes `localizable`, and `In-App Purchases.xcstrings` and
    /// `In.App.Purchases.xcstrings` both become `inAppPurchases`. A name that
    /// would start with a digit is prefixed with `_`, and an empty one is
    /// `catalog`. Reserved words are returned as they are; ``emit(_:)``
    /// writes them in backticks.
    package static func propertyName(forFileName fileName: String) -> String {
        var stem = fileName[...]
        if let dot = stem.lastIndex(of: ".") { stem = stem[..<dot] }
        let words = stem.unicodeScalars
            .split { !$0.properties.isXIDContinue }
            .map { String(String.UnicodeScalarView($0)) }
        var name = ""
        for (offset, word) in words.enumerated() {
            name += offset == 0 ? word.prefix(1).lowercased() + word.dropFirst() : word.prefix(1).uppercased() + word.dropFirst()
        }
        if name.isEmpty { name = "catalog" }
        if !isValidPropertyName(name) { name = "_" + name }
        return name
    }

    /// Whether `name` can be written as a Swift property name: an identifier
    /// head followed by identifier characters. Reserved words are valid
    /// because they are emitted in backticks; `_` alone is not a name.
    package static func isValidPropertyName(_ name: String) -> Bool {
        guard let first = name.unicodeScalars.first, first == "_" || first.properties.isXIDStart else { return false }
        return name != "_" && name.unicodeScalars.allSatisfy { $0.properties.isXIDContinue }
    }

    /// A problem with the name of a generated catalog accessor.
    package enum NameError: Error, Equatable, Sendable, CustomStringConvertible {
        case invalidName(String)
        case collision(name: String, first: String, second: String)

        package var description: String {
            switch self {
            case .invalidName(let name):
                "'\(name)' is not a valid Swift identifier for a catalog accessor"
            case .collision(let name, let first, let second):
                "string catalogs '\(first)' and '\(second)' both generate 'LocalizationCatalog.\(name)'; "
                    + "rename one of them so every catalog in a target has its own accessor"
            }
        }
    }

    /// The accessor name of each catalog, in order, or the first pair of
    /// catalogs whose names collide.
    ///
    /// `fileName` is the catalog's last path component and `path` is how it
    /// is named in a diagnostic.
    package static func propertyNames(
        forCatalogs catalogs: [(path: String, fileName: String)]
    ) throws(NameError) -> [String] {
        var owners: [String: String] = [:]
        var names: [String] = []
        for catalog in catalogs {
            let name = propertyName(forFileName: catalog.fileName)
            if let first = owners[name] {
                throw NameError.collision(name: name, first: first, second: catalog.path)
            }
            owners[name] = catalog.path
            names.append(name)
        }
        return names
    }

    package func emit(_ catalog: LocalizationCatalog) -> String {
        let name = Self.reservedWords.contains(propertyName) ? "`\(propertyName)`" : propertyName
        let access = accessLevel == "internal" ? "" : accessLevel + " "
        var output = """
            // Generated by SwiftLocalizationGenerator (format version \(Self.formatVersion)) from \(sourceFileName).
            // Do not edit. The catalog is the source of truth; this file is regenerated by
            // building with SwiftLocalizationPlugin, or by running:
            //   SwiftLocalizationGenerator \(sourceFileName) --output <file>.swift

            import SwiftLocalization

            extension LocalizationCatalog {
                /// The catalog generated from `\(sourceFileName)`.
                \(access)static let \(name): LocalizationCatalog = {
                    var entries: [String: LocalizationCatalog.Entry] = [:]
                    entries.reserveCapacity(\(catalog.entries.count))

            """
        for key in catalog.entries.keys.sorted(by: Self.precedes) {
            let localizations = catalog.entries[key]!.localizations
            output += "        entries[\(Self.literal(key))] = LocalizationCatalog.Entry(localizations: ["
            if localizations.isEmpty {
                output += ":])\n"
                continue
            }
            output += "\n"
            for locale in localizations.keys.sorted(by: { Self.precedes($0.identifier, $1.identifier) }) {
                let localization = localizations[locale]!
                output += "            LocaleIdentifier(\(Self.literal(locale.identifier))): LocalizationCatalog.Localization(\n"
                output += "                variation: \(variation(localization.variation, indent: 4))"
                if !localization.substitutions.isEmpty {
                    output += ",\n                substitutions: [\n"
                    for substitutionName in localization.substitutions.keys.sorted(by: Self.precedes) {
                        let substitution = localization.substitutions[substitutionName]!
                        output += "                    \(Self.literal(substitutionName)): LocalizationCatalog.Substitution(\n"
                        output += "                        argumentIndex: \(substitution.argumentIndex.map(String.init) ?? "nil"),\n"
                        output += "                        formatSpecifier: \(Self.literal(substitution.formatSpecifier)),\n"
                        output += "                        variation: \(variation(substitution.variation, indent: 6))\n"
                        output += "                    ),\n"
                    }
                    output += "                ]"
                }
                output += "\n            ),\n"
            }
            output += "        ])\n"
        }
        output += """
                    return LocalizationCatalog(
                        sourceLanguage: LocaleIdentifier(\(Self.literal(catalog.sourceLanguage.identifier))),
                        entries: entries
                    )
                }()
            }

            """
        return output
    }

    private func variation(_ variation: LocalizationCatalog.Variation, indent: Int) -> String {
        let padding = String(repeating: "    ", count: indent)
        switch variation {
        case .string(let format):
            return "LocalizationCatalog.Variation.string(\(Self.literal(format)))"
        case .plural(let type, let cases):
            var output = "LocalizationCatalog.Variation.plural(PluralRuleType.\(type.rawValue), [\n"
            for category in PluralCategory.allCases {
                guard let next = cases[category] else { continue }
                output += "\(padding)    PluralCategory.\(category.rawValue): \(self.variation(next, indent: indent + 1)),\n"
            }
            return output + "\(padding)])"
        case .device(let cases):
            var output = "LocalizationCatalog.Variation.device([\n"
            for device in cases.keys.sorted(by: Self.precedes) {
                output += "\(padding)    \(Self.literal(device)): \(self.variation(cases[device]!, indent: indent + 1)),\n"
            }
            return output + "\(padding)])"
        }
    }

    /// Orders by UTF-8 bytes so output does not depend on Unicode tables.
    private static func precedes(_ lhs: String, _ rhs: String) -> Bool {
        lhs.utf8.lexicographicallyPrecedes(rhs.utf8)
    }

    /// A single-line Swift string literal.
    static func literal(_ string: String) -> String {
        var output = "\""
        for scalar in string.unicodeScalars {
            switch scalar {
            case "\"": output += "\\\""
            case "\\": output += "\\\\"
            case "\n": output += "\\n"
            case "\r": output += "\\r"
            case "\t": output += "\\t"
            case _ where scalar.value < 0x20 || scalar.value == 0x7F
                || scalar.value == 0x85 || scalar.value == 0x2028 || scalar.value == 0x2029:
                output += "\\u{\(String(scalar.value, radix: 16))}"
            default:
                output.unicodeScalars.append(scalar)
            }
        }
        return output + "\""
    }

    private static let reservedWords: Set<String> = [
        "as", "associatedtype", "break", "case", "catch", "class", "continue", "default", "defer", "deinit",
        "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate", "for", "func", "guard", "if",
        "import", "in", "init", "inout", "internal", "is", "let", "nil", "operator", "private", "protocol",
        "public", "repeat", "rethrows", "return", "self", "static", "struct", "subscript", "super", "switch",
        "throw", "throws", "true", "try", "typealias", "var", "where", "while",
    ]
}
