import Foundation
import Testing

// These tests build Tests/Fixtures/PluginConsumer with the real
// `SwiftLocalizationPlugin` through a nested SwiftPM invocation. The fixture
// is copied to a temporary directory and built in a scratch directory inside
// it, so the nested build shares nothing with the build running the tests and
// writes nothing into the repository. The fixture's only dependency is this
// repository by path; no network access is involved.

#if !os(Windows)
@Suite struct PluginBuildTests {
    static let fixture = repositoryRoot.appendingPathComponent("Tests/Fixtures/PluginConsumer")
    static let sharedCatalog = repositoryRoot.appendingPathComponent("Tests/Fixtures/Localizable.xcstrings")
    static let catalogs = [
        "Sources/Distinct/Foo-Bar.xcstrings",
        "Sources/Colliding/Foo-Bar.xcstrings",
        "Sources/Colliding/Sub/Foo Bar.xcstrings",
    ]

    private func contents(of root: URL) throws -> [Data] {
        try Self.catalogs.map { try Data(contentsOf: root.appendingPathComponent($0)) }
    }

    /// One test for both targets so that they share a single nested build of
    /// the package and its generator.
    @Test(.timeLimit(.minutes(15)))
    func buildsDistinctCatalogsAndRejectsCollidingOnes() throws {
        let directory = try TemporaryDirectory()
        let package = directory.file("PluginConsumer")
        let scratch = directory.file("scratch")
        try FileManager.default.copyItem(at: Self.fixture, to: package)
        let manifest = try String(contentsOf: package.appendingPathComponent("Package.swift.in"), encoding: .utf8)
            .replacingOccurrences(of: "@SWIFT_LOCALIZATION_PATH@", with: repositoryRoot.path)
        try Data(manifest.utf8).write(to: package.appendingPathComponent("Package.swift"))
        try FileManager.default.removeItem(at: package.appendingPathComponent("Package.swift.in"))

        // The second catalog of `Distinct` is the one the unit tests decode.
        let sharedCopy = package.appendingPathComponent("Sources/Distinct/Sub/Localizable.xcstrings")
        try FileManager.default.createDirectory(at: sharedCopy.deletingLastPathComponent(), withIntermediateDirectories: true)
        try FileManager.default.copyItem(at: Self.sharedCatalog, to: sharedCopy)

        let originals = try contents(of: Self.fixture)
        let sharedOriginal = try Data(contentsOf: Self.sharedCatalog)
        let swift = swiftExecutable()
        // Options go before the positional arguments: after `run <product>`
        // they would be passed to the product instead.
        func swiftPM(_ subcommand: String, _ arguments: [String]) throws -> ProcessResult {
            try run(
                swift.url,
                swift.prefix + [subcommand, "--package-path", package.path, "--scratch-path", scratch.path] + arguments,
                in: package
            )
        }

        // Two catalogs with distinct accessors: both are generated by the one
        // plugin command, and the program that uses both runs.
        let distinct = try swiftPM("run", ["Distinct"])
        #expect(distinct.status == 0, "\(distinct.output)")
        #expect(
            distinct.output.hasSuffix("Hello from Foo-Bar\n8 keys\nWinkelwagen\n3 elementy\n1 file in 3 folders\n"),
            "\(distinct.output)"
        )
        let generated = try swiftFiles(in: scratch).filter { $0.hasSuffix("+LocalizationCatalog.swift") }
        #expect(generated == ["Foo-Bar+LocalizationCatalog.swift", "Localizable+LocalizationCatalog.swift"])

        // Two catalogs with the same accessor: the plugin's command fails, so
        // no generated source exists for the compiler to reject.
        let colliding = try swiftPM("build", ["--target", "Colliding"])
        #expect(colliding.status != 0, "\(colliding.output)")
        let first = package.appendingPathComponent("Sources/Colliding/Foo-Bar.xcstrings").path
        let second = package.appendingPathComponent("Sources/Colliding/Sub/Foo Bar.xcstrings").path
        #expect(
            colliding.output.contains(
                "error: string catalogs '\(first)' and '\(second)' both generate 'LocalizationCatalog.fooBar'"
            ),
            "\(colliding.output)"
        )
        #expect(!colliding.output.contains("redeclaration"), "\(colliding.output)")
        #expect(!colliding.output.contains("Colliding.swift"), "\(colliding.output)")
        #expect(try swiftFiles(in: scratch).filter { $0.hasSuffix("+LocalizationCatalog.swift") } == generated)

        // The nested builds stayed inside the scratch directory.
        #expect(!FileManager.default.fileExists(atPath: package.appendingPathComponent(".build").path))

        // Catalogs are inputs only: neither the copies nor the checked-in
        // fixtures were rewritten.
        #expect(try contents(of: package) == originals)
        #expect(try contents(of: Self.fixture) == originals)
        #expect(try Data(contentsOf: sharedCopy) == sharedOriginal)
        #expect(try Data(contentsOf: Self.sharedCatalog) == sharedOriginal)
    }
}
#endif
